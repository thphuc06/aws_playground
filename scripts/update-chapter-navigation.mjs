import {build} from 'esbuild';
import {createRequire} from 'node:module';
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const result = await build({stdin: {contents: "export {chapters} from './src/content';", resolveDir: root}, bundle: true, platform: 'node', format: 'cjs', write: false, logLevel: 'silent'});
const module = {exports: {}};
new Function('module', 'exports', 'require', result.outputFiles[0].text)(module, module.exports, createRequire(import.meta.url));
const rows = module.exports.chapters.map(chapter => ({id: chapter.id, examVersions: chapter.examVersions ?? ['DVA-C02'], sections: chapter.sections.map(section => ({id: section.id}))}));
const text = `/** Generated by scripts/update-chapter-navigation.mjs. Route IDs only; no lesson bodies or question bank. */\nimport type {ExamVersionId} from './examVersions';\nexport interface ChapterNavigation {id:string;examVersions:ExamVersionId[];sections:{id:string}[]}\nexport const chapterNavigation:ChapterNavigation[]=${JSON.stringify(rows, null, 2)};\n`;
const target = resolve(root, 'src/chapterNavigation.ts');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== text) throw new Error('Chapter navigation metadata is stale. Run node scripts/update-chapter-navigation.mjs.');
} else writeFileSync(target, text);
console.log(`${rows.length} chapter navigation records ${process.argv.includes('--check') ? 'checked' : 'generated'}.`);
